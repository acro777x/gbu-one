/**
 * supabase/schema.sql is generated from supabase/schema.ts, and the owner
 * applies it by hand in the dashboard SQL editor. If the two drift apart, the
 * live project silently keeps whatever was pasted last - exactly how the
 * missing row level security policies went unnoticed. So the build fails here.
 *
 * Regenerate with: node tools/emit-sql.mjs
 */
import { readFileSync } from 'fs';
import { join } from 'path';
import { SCHEMA_SQL } from '../supabase/schema';

const generated = readFileSync(join(__dirname, '..', 'supabase', 'schema.sql'), 'utf8');
const header =
  '-- GBU One - Supabase schema. Generated from supabase/schema.ts by\n' +
  '-- tools/emit-sql.mjs; do not edit this file by hand.\n\n';

describe('generated schema', () => {
  it('matches the TypeScript source', () => {
    // TypeScript normalises CRLF inside a template literal, so the generated
    // file is compared LF-only (tools/emit-sql.mjs writes it that way).
    const expected = header + SCHEMA_SQL.replace(/^\n/, '').replace(/\r\n/g, '\n').trimEnd() + '\n';
    expect(generated).toBe(expected);
  });

  it('carries the row level security block the app depends on', () => {
    for (const needle of [
      'create or replace function public.is_moderator()',
      'create policy "moderators read own"',
      'create policy "pyq papers approved read"',
      'create policy "pyq papers insert pending"',
      'create policy "pyq papers moderator update"',
      'create policy "device tokens own"',
      'create policy "pyq moderator move"',
    ]) {
      expect(generated).toContain(needle);
    }
  });

  it('never spells the moderator check out as a subquery that row level security would filter', () => {
    const policies = generated.match(/create policy[\s\S]*?;/g) ?? [];
    expect(policies.length).toBeGreaterThan(20);
    for (const policy of policies) {
      // A policy is filtered by the row level security of every table it
      // touches, so it may never read public.moderators directly.
      expect(policy).not.toMatch(/from public\.moderators/i);
    }
    const callingHelper = policies.filter((policy) => policy.includes('is_moderator()'));
    expect(callingHelper.length).toBeGreaterThanOrEqual(6);
  });

  it('defines the moderator helper once, as a security definer function', () => {
    const definitions = generated.match(/create or replace function public\.is_moderator\(\)/g) ?? [];
    expect(definitions).toHaveLength(1);
    expect(generated).toMatch(/security definer[\s\S]{0,80}select exists \(\s*select 1 from public\.moderators/);
    expect(generated).toContain('grant execute on function public.is_moderator()');
  });
});