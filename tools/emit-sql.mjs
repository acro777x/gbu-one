/**
 * Emits supabase/schema.sql from the SCHEMA_SQL template in supabase/schema.ts.
 *
 * The live project is bootstrapped by pasting SQL into the Supabase dashboard
 * SQL editor, so the owner needs a plain .sql file to copy. Generating it from
 * the TypeScript keeps one source of truth; tests/schema_sql_sync.test.ts
 * fails the build if the two drift apart.
 *
 * Usage: node tools/emit-sql.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'supabase/schema.ts'), 'utf8');

const start = source.indexOf('export const SCHEMA_SQL = `');
if (start < 0) {
  console.error('Could not find SCHEMA_SQL in supabase/schema.ts');
  process.exit(1);
}
const bodyStart = source.indexOf('`', start) + 1;
const bodyEnd = source.lastIndexOf('`');
if (bodyEnd <= bodyStart) {
  console.error('SCHEMA_SQL template looks unfinished');
  process.exit(1);
}

// TypeScript normalises CRLF inside a template literal, so the generated file
// has to be LF-only to match what `SCHEMA_SQL` evaluates to in tests and to
// paste cleanly into the Supabase SQL editor.
const sql = source
  .slice(bodyStart, bodyEnd)
  .replace(/\r\n/g, '\n')
  .replace(/^\n/, '')
  .trimEnd() + '\n';
const header =
  '-- GBU One - Supabase schema. Generated from supabase/schema.ts by\n' +
  '-- tools/emit-sql.mjs; do not edit this file by hand.\n\n';

writeFileSync(join(root, 'supabase/schema.sql'), header + sql);
console.log(`wrote supabase/schema.sql (${sql.split('\n').length} lines)`);